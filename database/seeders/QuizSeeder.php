<?php

namespace Database\Seeders;

use App\Models\QuizOption;
use App\Models\QuizQuestion;
use App\Models\Specialty;
use Illuminate\Database\Seeder;

/**
 * Профорієнтаційний квіз «Яка спеціальність тобі підходить?».
 * Варіанти привʼязуються до спеціальностей за КОДОМ (121/123/181/071) —
 * якщо спеціальності ще немає, варіант сідається без привʼязки (нейтральний).
 */
class QuizSeeder extends Seeder
{
    public function run(): void
    {
        $byCode = Specialty::query()->pluck('id', 'code');

        $questions = [
            ['Чим би ти зайнявся у вільний вечір?', [
                ['Писав би власну гру або застосунок', '121'],
                ['Розібрав би компʼютер і зібрав назад', '123'],
                ['Приготував би щось нове на кухні', '181'],
                ['Розклав би свої фінанси по поличках', '071'],
            ]],
            ['Який шкільний предмет тобі найближчий?', [
                ['Інформатика — алгоритми та код', '121'],
                ['Фізика — як усе працює всередині', '123'],
                ['Хімія та біологія', '181'],
                ['Математика — точність і розрахунки', '071'],
            ]],
            ['Твоя суперсила в команді?', [
                ['Придумати логіку рішення', '121'],
                ['Полагодити те, що ніхто не може', '123'],
                ['Зробити так, щоб усім смакувало', '181'],
                ['Тримати порядок у цифрах і документах', '071'],
            ]],
            ['Що звучить як робота мрії?', [
                ['Розробник в IT-компанії', '121'],
                ['Інженер з мереж або кіберзахисту', '123'],
                ['Технолог на сучасному виробництві', '181'],
                ['Бухгалтер або фінансовий аналітик', '071'],
            ]],
            ['Обери свій інструмент:', [
                ['Редактор коду', '121'],
                ['Паяльник і викрутка', '123'],
                ['Ваги і термометр', '181'],
                ['Калькулятор і таблиці', '071'],
            ]],
            ['Що тебе найбільше драйвить?', [
                ['Коли мій код оживає', '121'],
                ['Коли техніка слухається', '123'],
                ['Коли результат можна скуштувати', '181'],
                ['Коли баланс зійшовся до копійки', '071'],
            ]],
        ];

        foreach ($questions as $i => [$text, $options]) {
            $question = QuizQuestion::firstOrCreate(
                ['question' => $text],
                ['sort_order' => $i + 1, 'is_active' => true]
            );

            if ($question->options()->exists()) {
                continue; // питання вже наповнене — не дублюємо варіанти
            }

            foreach ($options as $j => [$label, $code]) {
                QuizOption::create([
                    'quiz_question_id' => $question->id,
                    'label' => $label,
                    'specialty_id' => $byCode[$code] ?? null,
                    'points' => 1,
                    'sort_order' => $j + 1,
                ]);
            }
        }
    }
}
